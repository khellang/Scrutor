using System.Collections.Generic;
using System.Linq;
using Microsoft.CodeAnalysis;
using Scrutor.Generators.Models;
using Scrutor.Generators.Utilities;

namespace Scrutor.Generators.Emitters;

/// <summary>
/// Emits C# source code for interceptors that replace Scan() calls at compile time.
/// </summary>
internal static class InterceptorEmitter
{
    /// <summary>
    /// Generates the complete source file with interceptor methods.
    /// </summary>
    public static string Emit(
        IEnumerable<ScanInterceptorInfo> interceptorInfos,
        IEnumerable<ServiceRegistration> attributeRegistrations,
        Compilation compilation)
    {
        var builder = new SourceBuilder();
        var interceptorList = interceptorInfos.ToList();
        var attributeList = attributeRegistrations.ToList();

        EmitFileHeader(builder);
        EmitInterceptsLocationAttribute(builder);
        EmitNamespace(builder, interceptorList, attributeList, compilation);

        return builder.ToString();
    }

    private static void EmitFileHeader(SourceBuilder builder)
    {
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
    }

    private static void EmitInterceptsLocationAttribute(SourceBuilder builder)
    {
        builder.AppendLine("namespace System.Runtime.CompilerServices");
        builder.OpenBrace();
        builder.AppendLine("[global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = true)]");
        builder.AppendLine("file sealed class InterceptsLocationAttribute : global::System.Attribute");
        builder.OpenBrace();
        builder.AppendLine("public InterceptsLocationAttribute(string filePath, int line, int column) { }");
        builder.CloseBrace();
        builder.CloseBrace();
        builder.AppendLine();
    }

    private static void EmitNamespace(
        SourceBuilder builder,
        List<ScanInterceptorInfo> interceptorInfos,
        List<ServiceRegistration> attributeRegistrations,
        Compilation compilation)
    {
        builder.AppendLine("namespace Scrutor.Generated");
        builder.OpenBrace();

        EmitInterceptorClass(builder, interceptorInfos, attributeRegistrations, compilation);

        builder.CloseBrace();
    }

    private static void EmitInterceptorClass(
        SourceBuilder builder,
        List<ScanInterceptorInfo> interceptorInfos,
        List<ServiceRegistration> attributeRegistrations,
        Compilation compilation)
    {
        var className = GetClassName(compilation.AssemblyName);

        builder.AppendLine("/// <summary>");
        builder.AppendLine("/// Interceptors for Scrutor Scan() method calls, generated at compile time.");
        builder.AppendLine("/// </summary>");
        builder.AppendLine("[global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"Scrutor.Generators\", \"1.0.0\")]");
        builder.AppendLine($"file static class {className}");
        builder.OpenBrace();

        foreach (var info in interceptorInfos)
        {
            EmitInterceptorMethod(builder, info, attributeRegistrations, compilation);
        }

        builder.CloseBrace();
    }

    private static string GetClassName(string? assemblyName)
    {
        if (string.IsNullOrEmpty(assemblyName))
        {
            return "ScrutorScanInterceptors";
        }

        var sanitized = new string(assemblyName!
            .Replace(".", "")
            .Replace("-", "")
            .Replace(" ", "")
            .Where(c => char.IsLetterOrDigit(c) || c == '_')
            .ToArray());

        return $"{sanitized}ScanInterceptors";
    }

    private static void EmitInterceptorMethod(
        SourceBuilder builder,
        ScanInterceptorInfo info,
        List<ServiceRegistration> attributeRegistrations,
        Compilation compilation)
    {
        builder.AppendLine();

        // Emit call chain documentation
        EmitCallChainComment(builder, info);

        var escapedPath = EscapeString(info.FilePath);
        builder.AppendLine($"[global::System.Runtime.CompilerServices.InterceptsLocation(\"{escapedPath}\", {info.Line}, {info.Column})]");

        builder.AppendLine($"public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection Scan_{info.Id}(");
        builder.Indent();
        builder.AppendLine("this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services,");
        builder.AppendLine("global::System.Action<global::Scrutor.ITypeSourceSelector> action)");
        builder.Unindent();
        builder.OpenBrace();

        if (info.HasUnsupportedPatterns)
        {
            builder.AppendLine($"// Warning: {info.UnsupportedPatternDescription ?? "Unsupported pattern"}");
            builder.AppendLine("// Falling back to runtime scanning");
            builder.AppendLine("global::Scrutor.ServiceCollectionExtensions.Scan(services, action);");
        }
        else if (info.UsesAttributes)
        {
            EmitAttributeRegistrations(builder, attributeRegistrations);
        }
        else
        {
            // Use type discovery to find matching types
            var discoveredRegistrations = TypeDiscoveryService.DiscoverRegistrations(
                info.Configuration,
                compilation);

            if (discoveredRegistrations.Count > 0)
            {
                EmitDiscoveredRegistrations(builder, discoveredRegistrations, info.Configuration);
            }
            else
            {
                builder.AppendLine("// No matching types discovered");
            }
        }

        builder.AppendLine();
        builder.AppendLine("return services;");

        builder.CloseBrace();
    }

    private static void EmitAttributeRegistrations(SourceBuilder builder, List<ServiceRegistration> registrations)
    {
        if (registrations.Count == 0)
        {
            builder.AppendLine("// No [ServiceDescriptor] attributes found");
            return;
        }

        builder.AppendLine("// Registrations from [ServiceDescriptor] attributes");

        foreach (var registration in registrations)
        {
            EmitRegistration(builder, registration);
        }
    }

    private static void EmitDiscoveredRegistrations(
        SourceBuilder builder,
        List<ServiceRegistration> registrations,
        ScanConfiguration config)
    {
        builder.AppendLine("// Registrations discovered from type scanning");

        foreach (var registration in registrations)
        {
            EmitRegistration(builder, registration);
        }
    }

    private static void EmitRegistration(SourceBuilder builder, ServiceRegistration registration)
    {
        var (methodName, useDescriptor) = registration.Strategy switch
        {
            RegistrationStrategyKind.Skip => ("TryAdd", true),
            RegistrationStrategyKind.Replace => ("Replace", true),
            _ => GetAppendMethod(registration.Lifetime, registration.ServiceKey != null)
        };

        if (registration.ServiceKey != null)
        {
            EmitKeyedRegistration(builder, registration, methodName, useDescriptor);
        }
        else
        {
            EmitNonKeyedRegistration(builder, registration, methodName, useDescriptor);
        }
    }

    private static (string method, bool useDescriptor) GetAppendMethod(ServiceLifetime lifetime, bool isKeyed)
    {
        if (isKeyed)
        {
            return lifetime switch
            {
                ServiceLifetime.Singleton => ("AddKeyedSingleton", false),
                ServiceLifetime.Scoped => ("AddKeyedScoped", false),
                ServiceLifetime.Transient => ("AddKeyedTransient", false),
                _ => ("AddKeyedTransient", false)
            };
        }

        return lifetime switch
        {
            ServiceLifetime.Singleton => ("AddSingleton", false),
            ServiceLifetime.Scoped => ("AddScoped", false),
            ServiceLifetime.Transient => ("AddTransient", false),
            _ => ("AddTransient", false)
        };
    }

    private static void EmitNonKeyedRegistration(
        SourceBuilder builder,
        ServiceRegistration registration,
        string methodName,
        bool useDescriptor)
    {
        var serviceType = registration.ServiceTypeFullName;
        var implementationType = registration.ImplementationTypeFullName;

        // Handle forwarding registrations (AsSelfWithInterfaces pattern)
        if (registration.ForwardsToImplementation)
        {
            builder.AppendLine($"services.{methodName}<{serviceType}>(sp => sp.GetRequiredService<{implementationType}>());");
            return;
        }

        // Open generics must use typeof() syntax
        if (registration.IsOpenGeneric)
        {
            if (useDescriptor)
            {
                var lifetime = GetLifetimeExpression(registration.Lifetime);
                if (methodName == "TryAdd")
                {
                    builder.AppendLine($"global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAdd(services, new global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor(typeof({serviceType}), typeof({implementationType}), {lifetime}));");
                }
                else if (methodName == "Replace")
                {
                    builder.AppendLine($"global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.Replace(services, new global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor(typeof({serviceType}), typeof({implementationType}), {lifetime}));");
                }
            }
            else
            {
                builder.AppendLine($"services.{methodName}(typeof({serviceType}), typeof({implementationType}));");
            }
        }
        else if (useDescriptor)
        {
            var lifetime = GetLifetimeExpression(registration.Lifetime);

            if (methodName == "TryAdd")
            {
                builder.AppendLine($"global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAdd(services, new global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor(typeof({serviceType}), typeof({implementationType}), {lifetime}));");
            }
            else if (methodName == "Replace")
            {
                builder.AppendLine($"global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.Replace(services, new global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor(typeof({serviceType}), typeof({implementationType}), {lifetime}));");
            }
        }
        else
        {
            builder.AppendLine($"services.{methodName}<{serviceType}, {implementationType}>();");
        }
    }

    private static void EmitKeyedRegistration(
        SourceBuilder builder,
        ServiceRegistration registration,
        string methodName,
        bool useDescriptor)
    {
        var serviceType = registration.ServiceTypeFullName;
        var implementationType = registration.ImplementationTypeFullName;
        var serviceKey = EscapeString(registration.ServiceKey!);

        // Handle forwarding registrations (AsSelfWithInterfaces pattern)
        if (registration.ForwardsToImplementation)
        {
            builder.AppendLine($"services.{methodName}<{serviceType}>(\"{serviceKey}\", (sp, key) => sp.GetRequiredKeyedService<{implementationType}>(key));");
            return;
        }

        // Open generics must use typeof() syntax
        if (registration.IsOpenGeneric)
        {
            if (useDescriptor)
            {
                var lifetime = GetLifetimeExpression(registration.Lifetime);
                if (methodName == "TryAdd")
                {
                    builder.AppendLine($"global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAdd(services, new global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor(typeof({serviceType}), \"{serviceKey}\", typeof({implementationType}), {lifetime}));");
                }
                else if (methodName == "Replace")
                {
                    builder.AppendLine($"global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.Replace(services, new global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor(typeof({serviceType}), \"{serviceKey}\", typeof({implementationType}), {lifetime}));");
                }
            }
            else
            {
                builder.AppendLine($"services.{methodName}(\"{serviceKey}\", typeof({serviceType}), typeof({implementationType}));");
            }
        }
        else if (useDescriptor)
        {
            var lifetime = GetLifetimeExpression(registration.Lifetime);

            if (methodName == "TryAdd")
            {
                builder.AppendLine($"global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAdd(services, new global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor(typeof({serviceType}), \"{serviceKey}\", typeof({implementationType}), {lifetime}));");
            }
            else if (methodName == "Replace")
            {
                builder.AppendLine($"global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.Replace(services, new global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor(typeof({serviceType}), \"{serviceKey}\", typeof({implementationType}), {lifetime}));");
            }
        }
        else
        {
            builder.AppendLine($"services.{methodName}<{serviceType}, {implementationType}>(\"{serviceKey}\");");
        }
    }

    private static string GetLifetimeExpression(ServiceLifetime lifetime)
    {
        return lifetime switch
        {
            ServiceLifetime.Singleton => "global::Microsoft.Extensions.DependencyInjection.ServiceLifetime.Singleton",
            ServiceLifetime.Scoped => "global::Microsoft.Extensions.DependencyInjection.ServiceLifetime.Scoped",
            ServiceLifetime.Transient => "global::Microsoft.Extensions.DependencyInjection.ServiceLifetime.Transient",
            _ => "global::Microsoft.Extensions.DependencyInjection.ServiceLifetime.Transient"
        };
    }

    private static void EmitCallChainComment(SourceBuilder builder, ScanInterceptorInfo info)
    {
        builder.AppendLine("/// <summary>");
        builder.AppendLine($"/// Intercepts Scan() call at {System.IO.Path.GetFileName(info.FilePath)}:{info.Line}");
        builder.AppendLine("/// </summary>");

        if (!string.IsNullOrEmpty(info.CallChainText))
        {
            builder.AppendLine("/// <remarks>");
            builder.AppendLine("/// <code>");
            builder.AppendLine($"/// {EscapeXmlComment(info.CallChainText!)}");
            builder.AppendLine("/// </code>");
            builder.AppendLine("/// </remarks>");
        }
    }

    private static string EscapeXmlComment(string value)
    {
        return value
            .Replace("&", "&amp;")
            .Replace("<", "&lt;")
            .Replace(">", "&gt;");
    }

    private static string EscapeString(string value)
    {
        return value
            .Replace("\\", "\\\\")
            .Replace("\"", "\\\"")
            .Replace("\n", "\\n")
            .Replace("\r", "\\r")
            .Replace("\t", "\\t");
    }
}
